-- Staff login and roles (ADR-0017). Only a BCrypt hash of the password is stored.
CREATE TABLE staff_account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(40)  NOT NULL,
    password_hash   VARCHAR(100) NOT NULL,
    role            VARCHAR(10)  NOT NULL,
    failed_attempts INT          NOT NULL DEFAULT 0,
    locked_until    TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_staff_username UNIQUE (username),
    CONSTRAINT ck_staff_role CHECK (role IN ('OPS', 'ADMIN'))
);

-- Who recorded each disruption. Null for rows recorded before staff accounts existed.
ALTER TABLE disruption ADD COLUMN recorded_by VARCHAR(40);
