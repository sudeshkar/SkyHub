-- Refunds that must not be forgotten (ADR-0030).
-- A charge that was taken for a booking that then failed, and whose refund also failed. Before this the charge id lived only in a log line.
CREATE TABLE unrefunded_charge (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_id       VARCHAR(64)   NOT NULL,
    amount          NUMERIC(12,2) NOT NULL,
    currency        VARCHAR(3)    NOT NULL,
    reason          VARCHAR(100)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts        INT           NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    refunded_at     TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_unrefunded_charge UNIQUE (charge_id)
);
-- Only unfinished rows are ever searched, so the index holds only those.
CREATE INDEX ix_unrefunded_due ON unrefunded_charge (next_attempt_at) WHERE refunded_at IS NULL;

-- Retry bookkeeping for refunds owed after a cancellation (ADR-0016). Null means "not tried by the retry job yet".
ALTER TABLE payment ADD COLUMN refund_attempts INT NOT NULL DEFAULT 0;
ALTER TABLE payment ADD COLUMN refund_next_attempt_at TIMESTAMP WITH TIME ZONE;
CREATE INDEX ix_payment_refund_due ON payment (id) WHERE status = 'REFUND_DUE';
