-- One row per seat per flight per date. The unique constraint means there is exactly
-- one row to compete for, and @Version on it gives optimistic locking (ADR-0002).
CREATE TABLE seat_inventory (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number  VARCHAR(8)  NOT NULL,
    departure_date DATE        NOT NULL,
    seat_number    VARCHAR(4)  NOT NULL,
    row_number     INT         NOT NULL,
    letter         VARCHAR(1)  NOT NULL,
    cabin          VARCHAR(10) NOT NULL,
    status         VARCHAR(10) NOT NULL,
    pnr_locator    VARCHAR(6),
    version        BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_seat UNIQUE (flight_number, departure_date, seat_number)
);

CREATE TABLE pnr (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locator         VARCHAR(6)   NOT NULL,
    contact_email   VARCHAR(254) NOT NULL,
    status          VARCHAR(10)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    idempotency_key VARCHAR(64)  NOT NULL,
    CONSTRAINT uq_pnr_locator UNIQUE (locator),
    CONSTRAINT uq_pnr_idempotency_key UNIQUE (idempotency_key)
);

CREATE TABLE pnr_segment (
    pnr_id         BIGINT     NOT NULL REFERENCES pnr (id),
    segment_order  INT        NOT NULL,
    flight_number  VARCHAR(8) NOT NULL,
    departure_date DATE       NOT NULL,
    PRIMARY KEY (pnr_id, segment_order)
);

CREATE TABLE pnr_passenger (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pnr_id          BIGINT      NOT NULL REFERENCES pnr (id),
    passenger_order INT         NOT NULL,
    first_name      VARCHAR(50) NOT NULL,
    last_name       VARCHAR(50) NOT NULL
);
CREATE INDEX ix_passenger_pnr ON pnr_passenger (pnr_id);

CREATE TABLE pnr_passenger_seat (
    passenger_id  BIGINT     NOT NULL REFERENCES pnr_passenger (id),
    segment_order INT        NOT NULL,
    seat_number   VARCHAR(4) NOT NULL,
    PRIMARY KEY (passenger_id, segment_order)
);
