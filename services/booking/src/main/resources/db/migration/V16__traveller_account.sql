-- Traveller accounts (ADR-0033). The address is encrypted like every other personal datum; email_index is a keyed hash of it
-- (see PiiCipher.blindIndex), so an account can be found by address without the address being stored in the clear.
CREATE TABLE traveller_account (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(500) NOT NULL,
    email_index        VARCHAR(64)  NOT NULL,
    -- Null until the person has used an emailed link: choosing a password is what proves the address is theirs.
    password_hash      VARCHAR(100),
    verified_at        TIMESTAMP WITH TIME ZONE,
    -- Only the hash of the emailed token is kept, so a copy of this table cannot be used to take over an account.
    link_token_hash    VARCHAR(64),
    link_issued_at     TIMESTAMP WITH TIME ZONE,
    link_expires_at    TIMESTAMP WITH TIME ZONE,
    failed_attempts    INT          NOT NULL DEFAULT 0,
    locked_until       TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_traveller_account_email UNIQUE (email_index),
    CONSTRAINT ck_traveller_account_verified CHECK (password_hash IS NULL OR verified_at IS NOT NULL)
);
CREATE UNIQUE INDEX uq_traveller_account_link ON traveller_account (link_token_hash) WHERE link_token_hash IS NOT NULL;
