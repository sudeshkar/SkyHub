-- The names a traveller keeps on their account to fill a booking with (ADR-0078).
--
-- Names only, and encrypted like every other personal datum (PiiCipher), which is why the columns are TEXT: a 50-character name is
-- longer once it is encrypted. Deleted with the account.
CREATE TABLE saved_passenger (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES traveller_account (id) ON DELETE CASCADE,
    first_name TEXT   NOT NULL,
    last_name  TEXT   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
-- Every read is one account's names, oldest first.
CREATE INDEX ix_saved_passenger_account ON saved_passenger (account_id, id);
