-- Delays and cancellations (ADR-0014): the exception laid over the timetable, one row per flight and date.
CREATE TABLE disruption (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number     VARCHAR(8)   NOT NULL,
    departure_date    DATE         NOT NULL,
    type              VARCHAR(10)  NOT NULL,
    revised_departure TIMESTAMP WITH TIME ZONE,
    reason            VARCHAR(200) NOT NULL,
    recorded_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_disruption_flight UNIQUE (flight_number, departure_date),
    CONSTRAINT ck_disruption_delay_has_time CHECK ((type = 'DELAYED') = (revised_departure IS NOT NULL))
);
