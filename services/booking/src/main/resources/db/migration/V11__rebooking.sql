-- Audit trail of staff moving bookings off disrupted flights (ADR-0023). Append-only; no personal data.
CREATE TABLE rebooking (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locator       VARCHAR(40) NOT NULL,
    segment_index INT         NOT NULL,
    from_flight   VARCHAR(8)  NOT NULL,
    from_date     DATE        NOT NULL,
    to_flight     VARCHAR(8)  NOT NULL,
    to_date       DATE        NOT NULL,
    rebooked_by   VARCHAR(40) NOT NULL,
    rebooked_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_rebooking_locator ON rebooking (locator);
