-- Online check-in (ADR-0013). Kept out of the pnr tables on purpose: checking in never changes the booking row.
CREATE TABLE check_in (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locator           VARCHAR(6) NOT NULL REFERENCES pnr (locator),
    segment_index     INT        NOT NULL,
    passenger_index   INT        NOT NULL,
    boarding_sequence INT        NOT NULL,
    checked_in_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    -- One check-in per passenger per flight, even if two requests race.
    CONSTRAINT uq_check_in UNIQUE (locator, segment_index, passenger_index)
);

-- Next free boarding number per flight and date (see JdbcBoardingSequence).
CREATE TABLE boarding_sequence (
    flight_number  VARCHAR(8) NOT NULL,
    departure_date DATE       NOT NULL,
    next_value     INT        NOT NULL,
    PRIMARY KEY (flight_number, departure_date)
);
