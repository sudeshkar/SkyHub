-- What each booking paid (ADR-0015). No card data: only the provider's charge reference and the amount.
CREATE TABLE payment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    locator    VARCHAR(6)    NOT NULL REFERENCES pnr (locator),
    charge_id  VARCHAR(64)   NOT NULL,
    amount     NUMERIC(12,2) NOT NULL,
    currency   VARCHAR(3)    NOT NULL,
    status     VARCHAR(10)   NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_payment_locator UNIQUE (locator),
    CONSTRAINT ck_payment_amount CHECK (amount >= 0)
);
