-- One row per event that has been handled (ADR-0019). The unique event id is what makes the consumer idempotent:
-- the row is written before the email is sent, in the same transaction, so a second delivery finds it and stops.
CREATE TABLE sent_notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   UUID         NOT NULL,
    type       VARCHAR(60)  NOT NULL,
    locator    VARCHAR(40)  NOT NULL,
    -- Masked ("p****@example.com"): enough to recognise, not enough to harvest. The real address is never stored here.
    recipient  VARCHAR(254) NOT NULL,
    subject    VARCHAR(200) NOT NULL,
    sent_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_sent_notification_event UNIQUE (event_id)
);

CREATE INDEX ix_sent_notification_locator ON sent_notification (locator);
