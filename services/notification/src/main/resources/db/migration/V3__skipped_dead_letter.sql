-- Parked messages the replay must leave out (ADR-0037). A message on the dead-letter topic is named by its partition and offset;
-- the replay passes over the ones listed here and removes their rows once it has passed them. No message body is stored.
CREATE TABLE skipped_dead_letter (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kafka_partition INT          NOT NULL,
    kafka_offset    BIGINT       NOT NULL,
    reason        VARCHAR(200) NOT NULL,
    skipped_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_skipped_dead_letter UNIQUE (kafka_partition, kafka_offset)
);
